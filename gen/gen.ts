/* eslint-disable @typescript-eslint/no-explicit-any */
import { apis } from "@/content/apiContent";
import { spawnSync } from "child_process";
import * as fs from "fs";
import * as path from "path";

function sanitizeApiPrefix(prefix: string): string {
  return prefix.replace(/^\//, "").replace(/\//g, "-");
}

const appTypesDir = path.resolve("gen/output/appTypes");
const openApiDir = path.resolve("gen/output/openApi");

function runScript(command: string, args: string[]) {
  const result = spawnSync(command, args, { stdio: "inherit" });
  if (result.status !== 0) {
    console.error(`❌ Failed: ${command} ${args.join(" ")}`);
    process.exit(1);
  }
}

function cleanDefaultResponse(operation: any, pathKey: string, method: string) {
  const defaultResponse = operation.responses?.default;
  if (!defaultResponse) return;

  const desc = defaultResponse.description ?? "";

  if (desc.includes("import(")) {
    const content = defaultResponse.content;

    if (content && Object.keys(content).length > 0) {
      defaultResponse.description = "Default fallback response";
      console.log(
        `ℹ️ Cleaned 'default' description in ${method.toUpperCase()} ${pathKey}`,
      );
    } else {
      delete operation.responses.default;
      console.log(
        `🗑️ Removed empty 'default' in ${method.toUpperCase()} ${pathKey}`,
      );
    }
  }
}

// Step 1: Generate OpenAPI specs
for (const api of apis) {
  const name = sanitizeApiPrefix(api.apiPrefix);
  const typeOutputPath = path.join(appTypesDir, `${name}.d.ts`);
  const openApiOutputPath = path.join(openApiDir, `${name}.json`);

  console.log(`\n🔧 Generating types for: ${name}`);
  runScript("bun", [
    "gen/generateTypesWithTSMorph.ts",
    api.appTypeCompletePath,
    typeOutputPath,
  ]);

  console.log(`📄 Generating OpenAPI for: ${name}`);
  runScript("bun", ["gen/gen-openapi.ts", typeOutputPath, openApiOutputPath]);
}

// Step 2: Merge OpenAPI specs
console.log("\n🔀 Merging OpenAPI specs...");

const merged = {
  openapi: "3.0.0",
  info: { title: "Autogenerated OpenAPI", version: "1.0.0" },
  servers: [{ url: "http://localhost:3000/api/main" }],
  paths: {} as Record<string, any>,
  tags: [] as { name: string }[],
};

for (const api of apis) {
  const name = sanitizeApiPrefix(api.apiPrefix);
  const openApiFile = path.join(openApiDir, `${name}.json`);

  if (!fs.existsSync(openApiFile)) {
    console.warn(`⚠️ Missing OpenAPI file: ${openApiFile}`);
    continue;
  }

  const json = JSON.parse(fs.readFileSync(openApiFile, "utf-8"));
  merged.tags.push({ name: api.name });

  for (const [pathKey, operations] of Object.entries<any>(json.paths)) {
    const prefixedPath =
      path.posix.join(api.apiPrefix, pathKey).replace(/\/+$/, "") || "/";
    if (!merged.paths[prefixedPath]) merged.paths[prefixedPath] = {};

    for (const [method, operation] of Object.entries<any>(operations)) {
      operation.tags = operation.tags || [];
      if (!operation.tags.includes(api.name)) {
        operation.tags.push(api.name);
      }

      cleanDefaultResponse(operation, prefixedPath, method);
      merged.paths[prefixedPath][method] = operation;
    }
  }
}

const outputPath = path.join("gen", "output", "openApi", "openapi.json");
fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, JSON.stringify(merged, null, 2));

console.log(`✅ Final merged OpenAPI spec written to: ${outputPath}`);
